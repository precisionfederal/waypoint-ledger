/* PERF (2026-10-01): the home page reads its condition count from
   data/conditions-count.json (scripts/gen-conditions-count.mjs, run by
   cf/build-static.sh) instead of bundling data/conditions.json on first load.
   The count must always be the file's. */
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import COUNT from '../data/conditions-count.json';
import { CONDITIONS } from '../lib/conditions';

describe('the home page condition count', () => {
  it('equals the conditions the app reads from data/conditions.json', () => {
    expect(COUNT.conditions).toBe(CONDITIONS.length);
  });
  it('is regenerated by the static build', () => {
    expect(readFileSync('cf/build-static.sh', 'utf8')).toContain('node scripts/gen-conditions-count.mjs');
  });
  it('keeps data/conditions.json off the home page', () => {
    expect(readFileSync('app/page.tsx', 'utf8')).not.toMatch(/from '@\/lib\/conditions'/);
  });
});
